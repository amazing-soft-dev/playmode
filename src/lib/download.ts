import { strToU8, zipSync } from "fflate";

import type { License } from "./domain/types.ts";

/**
 * Game downloads (plan section 05, feature 3). Every downloaded file carries a comment header
 * naming the site, the creator and the chosen license, plus a note to open it only in a browser.
 * The zip is ready to upload to itch.io as an HTML5 game.
 */

export const LICENSE_NAMES: Record<License, string> = {
  "all-rights-reserved": "All rights reserved",
  "cc-by-4.0": "Creative Commons Attribution 4.0 (CC BY 4.0)",
  "cc-by-nc-4.0": "Creative Commons Attribution-NonCommercial 4.0 (CC BY-NC 4.0)",
  "cc0-1.0": "Creative Commons Zero 1.0 (CC0, public domain)",
};

export interface DownloadInfo {
  title: string;
  creator: string;
  license: License;
}

const clean = (text: string) => text.replace(/--/g, "-").replace(/[<>]/g, "").trim();

export function slugify(title: string): string {
  return (
    title
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[^\w\s-]/g, "")
      .trim()
      .replace(/[\s_-]+/g, "-")
      .slice(0, 60) || "playermode-game"
  );
}

/** Puts the PlayerMode header comment above the doctype. */
export function withLicenseHeader(html: string, info: DownloadInfo, madeOn = new Date()): string {
  const header = [
    "<!--",
    `  ${clean(info.title)}`,
    `  Made by ${clean(info.creator)} with PlayerMode (AI-generated game), ${madeOn.toISOString().slice(0, 10)}.`,
    `  License: ${LICENSE_NAMES[info.license]}.`,
    "  This is a self-contained HTML5 game. Open it in a web browser only.",
    "-->",
  ].join("\n");
  return `${header}\n${html.replace(/^\s*<!--\s*playermode:game[^>]*-->\s*/i, "")}`;
}

export function readme(info: DownloadInfo): string {
  return [
    `# ${clean(info.title)}`,
    "",
    `Made by ${clean(info.creator)} with PlayerMode. The game was generated by AI from the creator's prompt.`,
    "",
    "## License",
    "",
    LICENSE_NAMES[info.license],
    "",
    "## Play",
    "",
    "Open `index.html` in any modern web browser. The game needs no internet connection.",
    "",
    "## Upload to itch.io",
    "",
    "1. Create a new project and set **Kind of project** to **HTML**.",
    "2. Upload this zip and tick **This file will be played in the browser**.",
    "3. Set the embed size to the game's frame (for example 960 x 540) and enable fullscreen.",
    "",
  ].join("\n");
}

/** index.html plus README.md, zipped. */
export function buildZip(html: string, info: DownloadInfo, madeOn = new Date()): Uint8Array {
  return zipSync(
    {
      "index.html": strToU8(withLicenseHeader(html, info, madeOn)),
      "README.md": strToU8(readme(info)),
    },
    { level: 9 },
  );
}

/** Triggers a browser download of text or bytes. */
export function saveFile(name: string, data: string | Uint8Array, type: string): void {
  const part: BlobPart = typeof data === "string" ? data : new Uint8Array(data);
  const url = URL.createObjectURL(new Blob([part], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
